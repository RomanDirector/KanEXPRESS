-- ============================================================================
-- KanEXpress — orders.planned_delivery_date (плановая дата доставки Kaspi)
-- ============================================================================
-- У заказа в Kaspi Orders API две разные даты: creationDate ("дата получения
-- заказа", у нас уже orders.created_at) и plannedDeliveryDate ("планируемая
-- дата доставки") — раньше вторую наш синк вообще не читал и никуда не писал.
-- Нужна для дефолт-фильтра "сегодня" на главной странице продавца: заказ
-- должен попадать в "сегодня", если СЕГОДНЯ дата поступления ИЛИ СЕГОДНЯ
-- плановая дата доставки (объединение, не пересечение) — иначе то, что
-- пришло раньше, но везти именно сегодня, потеряется из вида.
--
-- Проверено на живых данных: поле разреженное (у этого продавца заполнено
-- только у ~1.7% заказов, преимущественно у ещё не завершённых) — это
-- ожидаемо, Kaspi, похоже, обнуляет его после архивации заказа, а не
-- недостаток синка.
-- ============================================================================

alter table public.orders
  add column if not exists planned_delivery_date timestamptz;

create index if not exists orders_seller_id_planned_delivery_date_idx
  on public.orders (seller_id, planned_delivery_date);
