-- ============================================================================
-- KanEXpress — отдельное поле orders.product_quantity
-- ============================================================================
-- Количество товара раньше вшивалось прямо в product_name строкой вида
-- "Название × N" — неудобно показывать отдельной строкой в UI и требует
-- парсинга текста. Заводим отдельную колонку; синк (lib/kaspi-sync.ts) и
-- бэкфилл (app/api/admin/backfill-product-names) заполняют её из
-- attributes.quantity позиций заказа в Kaspi API (сумма по всем позициям).
-- ============================================================================

alter table public.orders
  add column if not exists product_quantity integer;
