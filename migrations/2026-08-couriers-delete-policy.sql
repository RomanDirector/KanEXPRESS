-- ============================================================================
-- KanEXpress — недостающая admin DELETE-политика на couriers
-- ============================================================================
-- 2026-08-seller-panel-simplification.sql уже декларирует admin_delete_couriers,
-- но на проде этой политики нет (проверено через pg_policies) — судя по всему,
-- этот блок миграции не докатился до боевой БД. Без DELETE-политики RLS
-- по умолчанию запрещает удаление ВСЕМ ролям молча (0 строк, без ошибки) —
-- поэтому кнопка "Удалить курьера" в app/admin/couriers ничего не делала,
-- и курьер возвращался после обновления страницы. Добавляем недостающую
-- policy — идемпотентно, как и остальные.
-- ============================================================================

drop policy if exists admin_delete_couriers on public.couriers;
create policy admin_delete_couriers
  on public.couriers
  for delete
  using (public.is_admin());
