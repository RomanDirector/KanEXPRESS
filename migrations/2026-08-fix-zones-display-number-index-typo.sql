-- 2026-08-shared-zones.sql должен был заменить глобальный unique-индекс на
-- zones.display_number триггером check_zone_display_number_unique()
-- (уникальность в рамках zone_group_id, а не по всей таблице), и для этого
-- дропал `zones_display_number_unique` (с "e" на конце).
--
-- Реальный индекс в БД называется `zones_display_number_uniq` (БЕЗ "e") —
-- `drop index if exists` с неверным именем молча ничего не сделал, и старый
-- глобальный partial-индекс остался действовать параллельно с новым триггером.
--
-- Результат: copy_zones_to_new_seller() (триггер AFTER INSERT ON sellers)
-- намеренно копирует новому продавцу зоны с ТЕМИ ЖЕ display_number, что и у
-- существующих продавцов (это ожидаемо — одна логическая зона = N строк по
-- продавцу с одинаковым номером) — но старый глобальный индекс это запрещал,
-- поэтому РЕГИСТРАЦИЯ ЛЮБОГО НОВОГО ПРОДАВЦА падала с
-- "duplicate key value violates unique constraint zones_display_number_uniq".
--
-- Удаляем настоящий (правильно названный) индекс — триггер уже полностью
-- покрывает нужный инвариант (разные зоны -> разные номера), просто скоупит
-- его по zone_group_id, а не по всей таблице.
-- ============================================================================

drop index if exists public.zones_display_number_uniq;
