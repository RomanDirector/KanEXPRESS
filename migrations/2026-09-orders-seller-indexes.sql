-- ============================================================================
-- KanEXpress — индексы orders(seller_id, status) и orders(seller_id, created_at)
-- ============================================================================
-- В миграциях не нашлось ни одного индекса на orders под seller_id — а почти
-- каждый запрос к заказам на /dashboard (список, счётчики по статусам,
-- сортировка по дате) фильтрует по seller_id, часто вместе со status или с
-- ORDER BY created_at. Сейчас (сентябрь 2026, ~8.5k строк) это не заметно —
-- Postgres спокойно сканирует таблицу целиком, замеры времени ответа сейчас
-- упираются в сетевую задержку, а не в план запроса. Добавляем индексы
-- заранее, как дешёвую страховку на рост таблицы, а не как фикс измеренной
-- сейчас проблемы.
--
-- create index (без concurrently) в Supabase SQL Editor выполняется под
-- блокировкой — на текущем размере таблицы это доли секунды, отдельного
-- окна обслуживания не требуется.
-- ============================================================================

create index if not exists orders_seller_id_status_idx
  on public.orders (seller_id, status);

create index if not exists orders_seller_id_created_at_idx
  on public.orders (seller_id, created_at desc);
